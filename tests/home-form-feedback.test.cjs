const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {JSDOM}=require('jsdom');
const output=process.env.HOME_PREVIEW_HTML;
test('homepage form preserves choices, errors and focus through confirmation without sending',()=>{
 assert.ok(output,'Set HOME_PREVIEW_HTML to the built homepage');
 const dom=new JSDOM(fs.readFileSync(output,'utf8'),{url:'http://localhost/',runScripts:'outside-only'});
 const w=dom.window,d=w.document;
 w.matchMedia=()=>({matches:true});
 w.HTMLElement.prototype.scrollIntoView=function(){};
 w.fetch=()=>{throw Error('No network requests allowed in this test');};
 w.eval(fs.readFileSync('src/assets/js/home-estimate.js','utf8'));
 const set=(id,value)=>{const e=d.getElementById(id);e.value=value;e.dispatchEvent(new w.Event('change',{bubbles:true}));};
 const click=(selector)=>d.querySelector(selector).click();
 click('[data-step="1"] [data-next]');
 assert.equal(d.activeElement.id,'f-maker');
 assert.equal(d.getElementById('f-maker').getAttribute('aria-invalid'),'true');
 assert.equal(d.getElementById('f-maker').getAttribute('aria-describedby'),'home-error-maker');
 set('f-maker','AUDI');
 assert.equal(d.getElementById('f-maker').hasAttribute('aria-invalid'),false);
 const models=[...d.getElementById('f-model').options].map(o=>o.value);
 assert.ok(models.indexOf('A3')<models.indexOf('A8'));
 const selected=models.find(v=>v && v!=='other');set('f-model',selected);
 const label=d.getElementById('f-model').selectedOptions[0].textContent;
 set('f-year','わからない');set('f-mileage','わからない');
 click('[data-step="1"] [data-next]');
 assert.equal(d.activeElement.textContent.trim(),'STEP 2｜お客様情報');
 assert.equal(d.querySelector('[aria-current="step"]').dataset.stepIndicator,'2');
 set('f-name','動作確認');set('f-phone','09000000000');
 click('[data-step="2"] [data-next]');
 assert.equal(d.activeElement.textContent.trim(),'STEP 3｜入力内容の確認');
 assert.ok(d.getElementById('estimate-confirm').textContent.includes(label));
 click('[data-goto="1"]');
 assert.equal(d.getElementById('f-model').value,selected);
 assert.equal(d.activeElement.textContent.trim(),'STEP 1｜お車について');
 set('f-maker','other');
 assert.equal(d.querySelector('[data-field="makerOther"]').hidden,false);
 assert.equal(d.querySelector('[data-field="modelOther"]').hidden,false);
 dom.window.close();
});
